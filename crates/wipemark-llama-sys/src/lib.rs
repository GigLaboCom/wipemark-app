//!
//! `wipemark-llama-sys` — llama.cpp's build and its raw bindings, and
//! nothing about this product.
//!
//! One shared `ggml` with its backends as run-time-loaded libraries, and
//! `libllama` linked against it. See `PIN.md` for the pinned commit, the
//! prebuilt release, their evidence and the bump procedure.
//!
//! ## Build modes
//!
//! - default: no C++ is compiled, the bindings are absent and
//!   [`BUILT_NATIVE`] is `false`. A plain `cargo check` needs no cmake, no
//!   libclang, no download and no fetched `vendor/` tree.
//! - `--features native`: build.rs links llama.cpp at the pin — the
//!   prebuilt release of `GigLaboCom/llama-cpp-prebuilt` for the target by
//!   default ([`PREBUILT`]), an unpacked archive named by
//!   `WIPEMARK_LLAMA_PREBUILT`, or, with `WIPEMARK_LLAMA_SOURCE=1` or on a
//!   target nobody publishes, a cmake build of the fetched tree with
//!   bindgen — and the bindings are re-exported from this crate's root.
//!
//! No hand-written `unsafe` lives here: every call site is in
//! `wipemark_llama::ffi`.

#![allow(non_upper_case_globals)]
#![allow(non_camel_case_types)]
#![allow(non_snake_case)]

/// Whether this build linked the real ggml and llama.cpp libraries.
///
/// `false` for the default (shim) build, `true` under `--features native`.
/// The safe layer reads it to refuse by name rather than fail to link.
pub const BUILT_NATIVE: bool = cfg!(wipemark_llama_native);

/// Where the native build's ggml backend libraries are — the prebuilt
/// archive's `backends/`, or `$OUT_DIR/backends` of a source build: the
/// development default `Runtime::init` loads from. `None` in a shim build,
/// which has no backends at all.
#[cfg(wipemark_llama_native)]
pub const BACKENDS_DIR: Option<&str> = Some(env!("WIPEMARK_LLAMA_BACKENDS_DIR"));
/// Where the native build installed the ggml backend libraries. `None` in
/// a shim build, which has no backends at all.
#[cfg(not(wipemark_llama_native))]
pub const BACKENDS_DIR: Option<&str> = None;

/// Whether the linked llama.cpp is the prebuilt archive (`true`) or was
/// built from source here (`false`, and in a shim build).
pub const PREBUILT: bool = cfg!(wipemark_llama_prebuilt);

/// The llama.cpp this crate links, the ggml it vendors, and the prebuilt
/// release of it with the sha256 of every archive.
///
/// The same file is compiled into `build.rs`, which verifies a prebuilt
/// archive against it; `PIN.md` and `vendor/fetch.sh` are kept identical to
/// it, and the tests below keep the pieces consistent with one another.
pub mod pin;

// FFI bindings: `$OUT_DIR/bindings.rs`, written by build.rs only under
// `--features native` (which is also when it sets `wipemark_llama_native`)
// — generated by bindgen in a source build, copied from the archive in a
// prebuilt one.
#[cfg(wipemark_llama_native)]
#[allow(
    clippy::all,
    clippy::pedantic,
    unused_qualifications,
    missing_debug_implementations,
    improper_ctypes
)]
mod bindings {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

