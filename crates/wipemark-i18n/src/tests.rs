/// The chain is what makes a partial translation usable, so it must
/// always contain a catalogue that is complete.
///
/// *Contain*, not *end on*. `negotiate_languages` appends the default
/// only when the requested languages did not already ask for it, so a
/// desktop whose preference list reads `[en-US, ru]` gets that order
/// back and the chain ends on `ru`. That is the user's own ranking and
/// it is right; what would be wrong is a chain with no complete
/// catalogue anywhere in it, because then a missing translation has
/// nothing to fall through to.
#[test]
fn the_fallback_is_always_in_the_chain() {
    for preference in [
        LanguagePreference::System,
        LanguagePreference::parse("de").expect("tag"),
        LanguagePreference::parse("ru-RU").expect("tag"),
        LanguagePreference::parse("zxx").expect("tag"),
    ] {
        let chain: Vec<String> = crate::negotiate(&preference)
            .iter()
            .map(ToString::to_string)
            .collect();
        assert!(!chain.is_empty(), "{preference:?} negotiated to nothing");
        assert!(
            chain.iter().any(|language| language == FALLBACK_LANGUAGE),
            "{preference:?} produced {chain:?}, which has no complete catalogue in it"
        );

        let mut unique = chain.clone();
        unique.sort();
        unique.dedup();
        assert_eq!(
            unique.len(),
            chain.len(),
            "{preference:?} produced a chain with a repeated language: {chain:?}"
        );
    }
}

