// ─── Plural rules ────────────────────────────────────────────────────

/// Why Fluent, and not a key-value table.
///
/// Russian selects on four CLDR categories and the boundaries are not
/// "== 1": 1 is *one*, 2–4 are *few*, 5 and up are *many*. No amount of
/// `format!` at the call site gets there without the translator writing
/// Rust, and the call site does not know which language it is in. The
/// catalogue does.
#[test]
fn plural_categories_come_from_the_language_not_the_call_site() {
    const RU: &str = "\
files = { $count ->
    [one] { $count } файл
    [few] { $count } файла
   *[other] { $count } файлов
}
";
    const EN: &str = "\
files = { $count ->
    [one] { $count } file
   *[other] { $count } files
}
";

    let russian = Localizer::from_sources(&[("ru", RU)], Rendering::PlainText);
    let english = Localizer::from_sources(&[("en-US", EN)], Rendering::PlainText);
    let files = Message::ALL
        .iter()
        .find(|message| message.id() == "files")
        .copied();
    assert!(
        files.is_none(),
        "`files` is a fixture; if it ships, test it through Message instead"
    );

    for (count, russian_form, english_form) in [
        (1, "1 файл", "1 file"),
        (3, "3 файла", "3 files"),
        (5, "5 файлов", "5 files"),
        (21, "21 файл", "21 files"),
    ] {
        assert_eq!(
            russian.format_raw("files", &args!("count" => count)),
            Some(russian_form.to_owned()),
            "russian, {count}"
        );
        assert_eq!(
            english.format_raw("files", &args!("count" => count)),
            Some(english_form.to_owned()),
            "english, {count}"
        );
    }
}

// ─── Catalogue hygiene ───────────────────────────────────────────────

/// What `build.rs` saw and what rust-embed baked in have to be the same
/// set. They are produced by two different globs over the same tree, so
/// a directory that one includes and the other does not is a language
/// that either cannot be chosen or cannot be loaded.
#[test]
fn the_embedded_catalogues_are_the_ones_that_were_built() {
    let embedded: Vec<String> = languages().iter().map(ToString::to_string).collect();
    let built: Vec<String> = BUILT_LANGUAGES.iter().map(|s| (*s).to_owned()).collect();
    assert_eq!(embedded, built);
}

/// The directory name *is* the language tag: it is what `bundle` looks
/// up and what negotiation matches on. `en_US` or `EN-us` would embed
/// fine and never be selected.
#[test]
fn catalogue_directories_are_canonical_language_tags() {
    for directory in BUILT_LANGUAGES {
        let parsed: LanguageIdentifier = directory
            .parse()
            .unwrap_or_else(|error| panic!("i18n/{directory}/ is not a language tag: {error}"));
        assert_eq!(
            parsed.to_string(),
            directory,
            "i18n/{directory}/ is not the canonical spelling of {parsed}"
        );
    }
}

/// Every language carries its own name, and no two carry the same one —
/// a selector with two entries reading "English" is a selector nobody
/// can use.
#[test]
fn every_language_names_itself_distinctly() {
    let mut autonyms: Vec<&str> = available_languages()
        .iter()
        .map(|language| {
            assert!(
                !language.autonym.is_empty(),
                "{} has no language-autonym",
                language.id
            );
            assert_ne!(
                language.autonym,
                language.id.to_string(),
                "{} fell back to its tag instead of naming itself",
                language.id
            );
            language.autonym.as_str()
        })
        .collect();
    autonyms.sort_unstable();
    let count = autonyms.len();
    autonyms.dedup();
    assert_eq!(count, autonyms.len(), "two languages share an autonym");
}

/// The status bar shows all three theme labels at once. Two that read
/// the same in some language is a selector with an unreachable option,
/// and it is a property of the catalogue rather than of the widget —
/// which is why it is gated here and not in the app, where testing it
/// would mean flipping a process-wide language under parallel tests.
#[test]
fn the_theme_labels_are_distinct_in_every_language() {
    const LABELS: [Message; 3] = [
        Message::ThemeSystem,
        Message::ThemeLight,
        Message::ThemeDark,
    ];
    for language in languages() {
        let localizer = only(&language);
        let mut rendered: Vec<String> = LABELS
            .iter()
            .map(|message| localizer.format(*message))
            .collect();
        rendered.sort();
        rendered.dedup();
        assert_eq!(rendered.len(), LABELS.len(), "{language}: {rendered:?}");
    }
}

/// The language selector lists `System (English)` above `English`. A
/// translation of `language-system` that dropped everything but the
/// placeholder would produce two rows reading the same word, and the
/// one the user needs — the one that follows the desktop — would be
/// indistinguishable from the one that pins a language forever.
#[test]
fn the_system_row_never_reads_as_a_plain_language_name() {
    for language in languages() {
        let localizer = only(&language);
        for other in available_languages() {
            let row = localizer.format_args(
                Message::LanguageSystem,
                &args!("language" => other.autonym.clone()),
            );
            assert_ne!(
                row, other.autonym,
                "{language}: the System row is indistinguishable from the {} row",
                other.id
            );
        }
    }
}

