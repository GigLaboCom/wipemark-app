/// Whatever the desktop is set to, `System` has to produce a chain that
/// can render a window. A machine with `LC_ALL=C` is not an error.
#[test]
fn system_always_resolves_to_something_renderable() {
    let localizer = Localizer::new(&LanguagePreference::System, Rendering::Ui);
    assert!(!localizer.chain().is_empty());
    assert!(!localizer.format(Message::WindowTitle).is_empty());
}

/// The documented precedence, in one place. Every level is exercised,
/// including the one that is skipped because it is nonsense.
#[test]
fn a_flag_beats_the_environment_beats_the_config_beats_the_desktop() {
    let german = LanguagePreference::parse("de").expect("tag");
    let russian = LanguagePreference::parse("ru").expect("tag");

    assert_eq!(
        LanguagePreference::resolve_from(Some("de"), Some("ru"), Some(russian.clone())),
        german,
        "the flag is the last word"
    );
    assert_eq!(
        LanguagePreference::resolve_from(None, Some("de"), Some(russian.clone())),
        german,
        "the environment beats the config file"
    );
    assert_eq!(
        LanguagePreference::resolve_from(None, None, Some(russian.clone())),
        russian,
        "the config file beats the desktop"
    );
    assert_eq!(
        LanguagePreference::resolve_from(None, None, None),
        LanguagePreference::System,
        "with nothing set, follow the desktop"
    );

    // A level that is not a language tag is skipped rather than
    // swallowing the ones below it.
    assert_eq!(
        LanguagePreference::resolve_from(Some("not a language"), Some("de"), None),
        german,
        "a nonsense flag must not hide the environment"
    );
}

/// Asking for `de-AT` and getting `de` is negotiation working. Asking
/// for `pt-BR` and getting English is not, and the CLI says so.
#[test]
fn a_request_is_honoured_by_its_own_language_whatever_the_region() {
    let austrian = LanguagePreference::parse("de-AT").expect("tag");
    let german: LanguageIdentifier = "de".parse().expect("tag");
    let english: LanguageIdentifier = FALLBACK_LANGUAGE.parse().expect("tag");

    assert!(austrian.is_honoured_by(&german));
    assert!(!austrian.is_honoured_by(&english));
    assert!(
        LanguagePreference::System.is_honoured_by(&english),
        "following the desktop is honoured by whatever it resolved to"
    );
}
