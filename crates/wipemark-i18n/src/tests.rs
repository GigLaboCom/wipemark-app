//! The catalogue gates.
//!
//! A localization bug does not look like a failure. It looks like a
//! window that is 90% German, a label that reads `panel-pending`, a
//! number that is grammatically wrong in a language nobody on the team
//! reads, or a claim that is careful in English and reckless in
//! Russian. None of that stops a build, so all of it is checked here,
//! over every message and every language rather than over the ones
//! someone thought to spot-check.
//!
//! Two of these are product rules rather than i18n hygiene, and they
//! are the ones to delete first when checking that this suite can fail:
//! [`the_third_shelf_is_never_empty_in_any_language`] and
//! [`no_language_promises_more_than_the_product_does`].

use fluent_syntax::{ast, parser};
use unic_langid::LanguageIdentifier;
use wipemark_core::report::not_established;
use wipemark_core::{Confidence, UnicodeClass};

use crate::{
    args, available_languages, catalogue, LanguagePreference, Localizer, Message, Rendering,
    BUILT_LANGUAGES, FALLBACK_LANGUAGE,
};

/// Every shipped language, as ids.
fn languages() -> Vec<LanguageIdentifier> {
    available_languages()
        .iter()
        .map(|language| language.id.clone())
        .collect()
}

/// Arguments for a message, built from the variables its own pattern
/// declares. Generated by `build.rs`, so this cannot drift from the
/// catalogue the way a hand-written table would.
fn arguments(message: Message) -> crate::FluentArgs<'static> {
    let mut args = crate::FluentArgs::new();
    for variable in message.variables() {
        args.set(*variable, "x");
    }
    args
}

/// One language, no fallback behind it — so `defines` is the question
/// "is this translated" rather than "does something render".
fn only(language: &LanguageIdentifier) -> Localizer {
    Localizer::for_languages(std::slice::from_ref(language), Rendering::PlainText)
}

fn parse(source: &str) -> ast::Resource<&str> {
    match parser::parse(source) {
        Ok(resource) => resource,
        Err((_, errors)) => panic!("catalogue does not parse: {errors:?}"),
    }
}

fn message_ids(resource: &ast::Resource<&str>) -> Vec<String> {
    resource
        .body
        .iter()
        .filter_map(|entry| match entry {
            ast::Entry::Message(message) => Some(message.id.name.to_owned()),
            _ => None,
        })
        .collect()
}

// ─── Completeness ────────────────────────────────────────────────────

/// The headline gate: no language, through its own chain, renders a
/// message as its own id.
#[test]
fn every_message_renders_in_every_language() {
    for language in languages() {
        let localizer = Localizer::new(
            &LanguagePreference::Explicit(language.clone()),
            Rendering::PlainText,
        );
        for message in Message::ALL {
            let text = localizer.format_args(message, &arguments(message));
            assert!(
                !text.is_empty() && text != message.id(),
                "{language}: `{}` did not render",
                message.id()
            );
        }
    }
}

/// A *lagging* translation is a supported state — the chain exists for
/// it. A lagging translation that shipped is a review decision, so it
/// fails here, naming every key it is missing.
#[test]
fn shipped_languages_are_complete() {
    for language in languages() {
        let localizer = only(&language);
        let missing: Vec<&str> = Message::ALL
            .iter()
            .filter(|message| !localizer.defines(**message))
            .map(|message| message.id())
            .collect();
        assert!(
            missing.is_empty(),
            "{language} is missing {} of {} messages: {missing:?}",
            missing.len(),
            Message::ALL.len()
        );
    }
}

/// The other direction. A translator's typo produces a key nothing will
/// ever ask for, and the message it was meant to be stays English —
/// which looks exactly like "not translated yet" and is not.
#[test]
fn no_language_defines_a_message_nobody_asks_for() {
    let known: Vec<&str> = Message::ALL.iter().map(|message| message.id()).collect();
    for language in languages() {
        let source = catalogue::source(&language).expect("shipped catalogue");
        let orphans: Vec<String> = message_ids(&parse(&source))
            .into_iter()
            .filter(|id| !known.contains(&id.as_str()))
            .collect();
        assert!(
            orphans.is_empty(),
            "{language} defines keys that are not in the fallback catalogue: {orphans:?}"
        );
    }
}

/// A renamed `$variable` renders perfectly and means something else:
/// the value is dropped and the reader sees a sentence with a hole in
/// it. Compared over the syntax, not the output, because the output is
/// exactly what does *not* show the problem.
#[test]
fn variables_match_the_fallback() {
    let fallback: LanguageIdentifier = FALLBACK_LANGUAGE.parse().expect("fallback tag");
    for language in languages() {
        if language == fallback {
            continue;
        }
        let source = catalogue::source(&language).expect("shipped catalogue");
        let resource = parse(&source);
        for entry in &resource.body {
            let ast::Entry::Message(translated) = entry else {
                continue;
            };
            let Some(message) = Message::ALL
                .iter()
                .find(|message| message.id() == translated.id.name)
            else {
                continue; // covered by no_language_defines_a_message_nobody_asks_for
            };
            let mut found: Vec<String> = Vec::new();
            if let Some(pattern) = &translated.value {
                collect(pattern, &mut found);
            }
            found.sort();
            found.dedup();
            let expected: Vec<String> = message
                .variables()
                .iter()
                .map(|variable| (*variable).to_owned())
                .collect();
            assert_eq!(
                found,
                expected,
                "{language}: `{}` references different variables than en-US",
                message.id()
            );
        }
    }
}

fn collect(pattern: &ast::Pattern<&str>, found: &mut Vec<String>) {
    for element in &pattern.elements {
        if let ast::PatternElement::Placeable { expression } = element {
            collect_expression(expression, found);
        }
    }
}

fn collect_expression(expression: &ast::Expression<&str>, found: &mut Vec<String>) {
    match expression {
        ast::Expression::Inline(ast::InlineExpression::VariableReference { id }) => {
            found.push(id.name.to_owned());
        }
        ast::Expression::Inline(ast::InlineExpression::Placeable { expression }) => {
            collect_expression(expression, found);
        }
        ast::Expression::Inline(_) => {}
        ast::Expression::Select { selector, variants } => {
            if let ast::InlineExpression::VariableReference { id } = selector {
                found.push(id.name.to_owned());
            }
            for variant in variants {
                collect(&variant.value, found);
            }
        }
    }
}

// ─── Product rules ───────────────────────────────────────────────────

/// The third shelf, in every language.
///
/// `wipemark_core::report::not_established` is the list of claims the
/// product refuses to make. A fourth entry added there with no
/// translation would print English inside an otherwise German report —
/// which is the one place in this product where a reader skimming past
/// a paragraph they cannot read is a real cost. Deleting an arm of
/// `not_established::ALL`, or a `report-not-established-*` key from any
/// catalogue, has to turn this red.
#[test]
fn the_third_shelf_is_never_empty_in_any_language() {
    assert!(
        !not_established::ALL.is_empty(),
        "the third shelf is never empty"
    );

    for (id, canonical) in not_established::ALL {
        let key = format!("report-not-established-{id}");
        let message = Message::ALL
            .iter()
            .find(|message| message.id() == key)
            .unwrap_or_else(|| {
                panic!(
                    "`{id}` is on the third shelf but `{key}` is not in the catalogue \
                     (canonical English: {canonical:?})"
                )
            });

        for language in languages() {
            assert!(
                only(&language).defines(*message),
                "{language} has no translation for the third-shelf item `{id}`"
            );
        }
    }
}

/// The picture report's shelf, in every language: its first claim —
/// invisible marks in the pixels, not searched for, not removed — is
/// `wipemark-pixels`'s, and is the one sentence a reader of a cleaned
/// picture most needs. Deleting its key from any catalogue, or adding a
/// claim to the picture shelf with no key, turns this red.
#[test]
fn the_picture_shelf_is_never_empty_in_any_language() {
    let shelf = wipemark_pixels::not_established::shelf();
    assert_eq!(shelf.first(), Some(&wipemark_pixels::not_established::ID));
    for id in shelf {
        let key = format!("report-not-established-{id}");
        let message = Message::ALL
            .iter()
            .find(|message| message.id() == key)
            .unwrap_or_else(|| {
                panic!("`{id}` is on the picture shelf but `{key}` is not in the catalogue")
            });
        for language in languages() {
            assert!(
                only(&language).defines(*message),
                "{language} has no translation for the picture-shelf item `{id}`"
            );
        }
    }
}

/// A vendor or a product of a visible mark is an identifier (Q-V9):
/// interpolated beside a finding, never written into a sentence — a
/// catalogue string that named one would put a trademark into prose and go
/// stale the day the profile is renamed. Every `vendor` and `product` of
/// the compiled-in mark catalogue, in every language, in every message.
#[test]
fn no_catalogue_string_names_a_mark_vendor() {
    let mut names: Vec<String> = Vec::new();
    for key in ["\"vendor\":", "\"product\":"] {
        for (at, _) in wipemark_pixels::EMBEDDED.match_indices(key) {
            let rest = &wipemark_pixels::EMBEDDED[at + key.len()..];
            let Some(open) = rest.find('"') else { continue };
            let value = &rest[open + 1..];
            if let Some(close) = value.find('"') {
                let name = value[..close].to_lowercase();
                if !names.contains(&name) {
                    names.push(name);
                }
            }
        }
    }
    assert!(!names.is_empty(), "the mark catalogue names no vendor");
    for language in languages() {
        let localizer = only(&language);
        for message in Message::ALL {
            let text = localizer
                .format_args(message, &arguments(message))
                .to_lowercase();
            for name in &names {
                let named = text
                    .split(|c: char| !c.is_alphanumeric())
                    .any(|word| word == name);
                assert!(
                    !named,
                    "{language}: `{}` names {name:?} — a vendor is an identifier, \
                     interpolated, never part of a sentence",
                    message.id()
                );
            }
        }
    }
}

/// Every confidence `wipemark_core` has, listed by hand — core has no
/// `Confidence::ALL` — and kept honest by [`confidence_ordinal`]'s
/// exhaustive `match`: a fifth confidence does not compile there until
/// it is added here too.
const CONFIDENCES: [Confidence; 4] = [
    Confidence::LikelyFalsePositive,
    Confidence::Informational,
    Confidence::Probable,
    Confidence::Confirmed,
];

fn confidence_ordinal(confidence: Confidence) -> usize {
    match confidence {
        Confidence::LikelyFalsePositive => 0,
        Confidence::Informational => 1,
        Confidence::Probable => 2,
        Confidence::Confirmed => 3,
    }
}

/// What a finding is and how sure, in every language.
///
/// A report row reads "U+200B ZERO WIDTH SPACE · zero-width character ·
/// confirmed": the name is the standard's and never translated, and the
/// other two are this catalogue's, keyed by the stable ids
/// (`unicode-class-<id>`, `confidence-<id>`). A class added to core with
/// no key, or a key renamed in one catalogue, would print a key — or
/// English inside a German report — in exactly the line a reader needs.
#[test]
fn every_unicode_class_and_confidence_reads_in_every_language() {
    for (index, confidence) in CONFIDENCES.iter().enumerate() {
        assert_eq!(confidence_ordinal(*confidence), index, "{confidence:?}");
    }

    let keys = UnicodeClass::ALL
        .iter()
        .map(|class| format!("unicode-class-{}", class.as_str()))
        .chain(
            CONFIDENCES
                .iter()
                .map(|confidence| format!("confidence-{}", confidence.as_str())),
        );
    for key in keys {
        let message = Message::ALL
            .iter()
            .find(|message| message.id() == key)
            .unwrap_or_else(|| panic!("`{key}` is not in the catalogue"));
        for language in languages() {
            assert!(
                only(&language).defines(*message),
                "{language} has no translation for `{key}`"
            );
        }
    }
}

/// Rule 3 of the honesty contract, held in every language.
///
/// English is reviewed by everyone who reads this repo; a translation
/// is reviewed by whoever wrote it. "Undetectable" is a claim with no
/// oracle behind it — there is no test that could support it — so the
/// gate is on the words rather than on a reviewer's attention.
#[test]
fn no_language_promises_more_than_the_product_does() {
    /// Claims, not vocabulary. `evasion` and `detector` are absent on
    /// purpose: the third shelf says the product does *not* establish
    /// evasion of a vendor's detector, and a gate that banned the noun
    /// would ban the disclaimer.
    const FORBIDDEN: [&str; 12] = [
        // en
        "undetectable",
        "undetected",
        "untraceable",
        "foolproof",
        "guarantee",
        "100%",
        // de
        "unerkennbar",
        "nicht erkennbar",
        "garantiert",
        // ru
        "необнаружим",
        "неопределим",
        "гарантир",
    ];

    for language in languages() {
        let localizer = only(&language);
        for message in Message::ALL {
            let text = localizer
                .format_args(message, &arguments(message))
                .to_lowercase();
            for claim in FORBIDDEN {
                assert!(
                    !text.contains(claim),
                    "{language}: `{}` claims {claim:?} — there is no oracle for that \
                     (spec §0.1 rule 3)",
                    message.id()
                );
            }
        }
    }
}

/// The product's own rule, turned on the product's own strings.
///
/// Layer A removes zero-width characters, bidi controls, soft hyphens
/// and exotic spaces. A catalogue carrying one would put them into
/// every `--json` report and every file the CLI writes, and Wipemark
/// would flag its own output. Fluent's bidi isolation is the way this
/// happens by accident, which is why [`Rendering::PlainText`] exists
/// and why this test formats *with arguments* — the isolation marks
/// only appear around an interpolated value.
#[test]
fn no_message_carries_a_character_layer_a_would_strip() {
    for language in languages() {
        let localizer = only(&language);
        for message in Message::ALL {
            let text = localizer.format_args(message, &arguments(message));
            for (index, character) in text.char_indices() {
                assert!(
                    !stripped_by_layer_a(character),
                    "{language}: `{}` contains U+{:04X} at byte {index} — Layer A removes it",
                    message.id(),
                    character as u32
                );
            }
        }
    }
}

/// The classes `wipemark_core::UnicodeClass` marks for removal, as
/// ranges. Deliberately a second, independent spelling of the table:
/// this suite must not be able to pass because the classifier is wrong.
fn stripped_by_layer_a(character: char) -> bool {
    let code = character as u32;
    matches!(code,
        0x00AD                              // soft hyphen
        | 0x00A0 | 0x2000..=0x200A          // exotic spaces
        | 0x202F | 0x205F | 0x3000
        | 0x200B..=0x200F                   // zero width, ZWJ, LRM/RLM
        | 0x202A..=0x202E | 0x2060          // bidi embedding, word joiner
        | 0x2066..=0x2069                   // bidi isolates — Fluent's own
        | 0xFEFF
        | 0xFE00..=0xFE0F                   // variation selectors
        | 0xFDD0..=0xFDEF                   // noncharacters
        | 0xE000..=0xF8FF                   // private use
        | 0xE0000..=0xE007F                 // tag characters
        | 0xE0100..=0xE01EF
        | 0xF0000..=0xFFFFD
        | 0x100000..=0x10FFFD
    ) || (code & 0xFFFE) == 0xFFFE
}

/// The other half of the same decision. If `Rendering` made no
/// difference, [`no_message_carries_a_character_layer_a_would_strip`]
/// would pass for the wrong reason.
#[test]
fn a_window_isolates_what_a_pipe_must_not() {
    let english: LanguageIdentifier = FALLBACK_LANGUAGE.parse().expect("fallback tag");
    let args = args!("language" => "العربية");

    let ui = Localizer::for_languages(std::slice::from_ref(&english), Rendering::Ui)
        .format_args(Message::LanguageSystem, &args);
    let plain = Localizer::for_languages(std::slice::from_ref(&english), Rendering::PlainText)
        .format_args(Message::LanguageSystem, &args);

    assert!(
        ui.contains('\u{2068}') && ui.contains('\u{2069}'),
        "a window must isolate an interpolated value: {ui:?}"
    );
    assert!(
        !plain.contains('\u{2068}') && !plain.contains('\u{2069}'),
        "a pipe must not carry isolates: {plain:?}"
    );
    assert_eq!(
        ui.replace(['\u{2068}', '\u{2069}'], ""),
        plain,
        "the two renderings must differ only by the isolates"
    );
}

/// A window's localizer still has a road to plain text, per call: the
/// title it hands the platform. Every language, because the twin chain is
/// built per link.
#[test]
fn a_window_can_ask_for_plain_text_per_call() {
    let args = args!("language" => "עברית");
    for language in available_languages() {
        let ui = Localizer::for_languages(std::slice::from_ref(&language.id), Rendering::Ui);
        let isolated = ui.format_args(Message::LanguageSystem, &args);
        let plain = ui.format_args_plain(Message::LanguageSystem, &args);
        assert!(
            isolated.contains('\u{2068}'),
            "{}: {isolated:?}",
            language.id
        );
        assert!(
            !plain.contains(['\u{2068}', '\u{2069}']),
            "{}: a plain call carried isolates: {plain:?}",
            language.id
        );
        assert_eq!(isolated.replace(['\u{2068}', '\u{2069}'], ""), plain);
        assert_eq!(
            ui.format_plain(Message::SettingsTitle),
            ui.format(Message::SettingsTitle),
            "{}: a message with nothing interpolated reads the same",
            language.id
        );
        // And the localizer itself is still a window's.
        assert_eq!(ui.rendering(), Rendering::Ui);
        assert!(ui
            .format_args(Message::LanguageSystem, &args)
            .contains('\u{2068}'));
    }
}

